class Sessions:
    def __init__(self):
        self.items = {}

    def create(self, item):
        self.items[item.id] = item
        return item

    def get(self, sid):
        return self.items.get(sid)

    def list(self):
        return list(self.items.values())

    def set_primary_agent(self, sid, agent_id):
        return None


class Messages:
    def __init__(self):
        self.items = []

    def append(self, item):
        self.items.append(item)
        return item

    def list_by_session(self, sid):
        return [m for m in self.items if m.session_id == sid]


class ChunkProvider:
    def __init__(self, chunks):
        self.chunks = chunks
        self.request = None

    async def health(self):
        return True

    async def stream(self, request):
        self.request = request
        for chunk in self.chunks:
            yield ModelChunk(text=chunk)
        yield ModelChunk(text='', done=True)


def test_settings_low_latency_think_and_payload(tmp_path):
    settings = Settings(_env_file=None, data_dir=tmp_path, model_name='qwen3.5:9b')
    config = settings.model_runtime
    assert config.think is False
    provider = OllamaProvider('http://localhost:11434', think=config.think,
                              context_window=config.context_window,
                              max_output_tokens=config.max_output_tokens,
                              keep_alive=config.keep_alive)
    payload = provider._build_payload(ModelRequest(model=config.model,
        messages=(ModelMessage(role=MessageRole.USER, content='ola'),)), stream=True)
    assert payload['think'] is False
    assert payload['keep_alive'] == '20m'
    assert payload['options']['num_ctx'] == 4096
    assert payload['options']['num_predict'] == 320
    assert 'think' not in payload['options']


def test_compact_personas_preserve_identity_and_distinction():
    a = render_compact_persona(TODD)
    b = render_compact_persona(MORGANA)
    assert 'agente original' in a and 'agente' in b
    assert 'Jason Todd' in a and 'Oraculo' in b
    assert 'ironia seca' in a and 'curiosa' in b
    assert len(a) < len(TODD.persona_prompt)
    assert len(b) < len(MORGANA.persona_prompt)


@pytest.mark.asyncio
async def test_streaming_guard_does_not_expose_marker_across_chunks():
    provider = StreamingPromptLeakGuardProvider(ChunkProvider([
        'Trecho seguro de conversa e conteudo que veio antes. ' * 3,
        'IDENTIDADE E COMPORTAMENTO DO ', 'CAMPANARIO', ' um vazamento',
    ]))
    request = ModelRequest(model='fake', messages=(ModelMessage(role=MessageRole.USER, content='oi'),))
    with pytest.raises(Exception):
        output = ''.join(c.text async for c in provider.stream(request))
    # Confirmed: leak marker is blocked, including when split between model chunks.


@pytest.mark.asyncio
async def test_new_streaming_turn_preserves_unseen_natural_response():
    response = 'Tudo certo. Tava pensando numa ideia meio diferente hoje; depois eu te conto.'
    provider = StreamingPromptLeakGuardProvider(ChunkProvider([response[i:i+9] for i in range(0,len(response),9)]))
    sessions = Sessions()
    messages = Messages()
    service = ChatService(sessions, messages, provider, RecentMessagesContextManager(12),
                          'fake', low_latency_mode=True, live_streaming=True)
    session = service.create_session()
    events = [event async for event in service.stream_turn(session.id, 'e ai, o que ta pegando?')]
    chunks = [e.text for e in events if e.type == 'token']
    assert len(chunks) >= 2
    assert ''.join(chunks) == response
    assert messages.items[-1].content == response
    assert messages.items[-1].agent_id == 'morgana'

@pytest.mark.asyncio
async def test_fast_composition_does_not_replace_generated_greeting(tmp_path, monkeypatch):
    """A new greeting must be generated by the provider, not a fixed-answer DB rule."""
    from campanario import composition
    provider = ChunkProvider(["Fala! Que bom te ver por aqui."])
    monkeypatch.setattr(composition, 'build_model_provider', lambda _: provider)
    settings = Settings(_env_file=None, data_dir=tmp_path, model_name='fake-model',
                        low_latency_mode=True, live_streaming=True)
    service, _ = composition.build_chat_stack(settings,
        database_url='sqlite+pysqlite:///:memory:', create_schema=True)
    session = service.create_session()
    chunks = [event.text async for event in service.stream_turn(session.id, 'oi')
              if event.type == 'token']
    assert ''.join(chunks) == 'Fala! Que bom te ver por aqui.'
    assert 'CONVERSA NO CAMPANARIO' in provider.request.messages[0].content
    assert 'TRAITS CORE' not in provider.request.messages[0].content
